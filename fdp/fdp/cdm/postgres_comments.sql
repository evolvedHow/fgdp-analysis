-- postgres_comments.sql — Documentation for every fdga table, view and column.
--
-- Applied by scripts/load_fdga_to_postgres.py (every run, and via
-- --comments-only on its own). Idempotent: COMMENT ON always overwrites.
--
-- Why this file exists
-- --------------------
-- Metabase reads PostgreSQL COMMENT text over JDBC (exposed as REMARKS) and
-- uses it as the initial table and field description. That makes this file the
-- single source of documentation for both SQL users (\d+ in psql) and the
-- Metabase Table Metadata screen — write it once, both surfaces get it.
--
-- IMPORTANT — Metabase only reads these on FIRST sync
-- ---------------------------------------------------
-- Metabase populates descriptions when they are empty, and will not overwrite
-- a description that already exists on a later sync (metabase#38694). So:
--
--   * Apply this BEFORE adding the database to Metabase, and the descriptions
--     appear automatically.
--   * If the database is already connected and the fields have descriptions,
--     changing the text here will NOT propagate. Clear the description in
--     Admin > Table Metadata first, then re-sync — or remove and re-add the
--     database if you want a wholesale refresh.
--
-- Style: say what the column means and how to read it, not what it is named.
-- Call out units, nullability that carries meaning, and anything that would
-- lead an analyst to a wrong conclusion.

