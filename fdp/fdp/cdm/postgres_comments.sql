COMMENT ON TABLE fdga.corrections IS
$$Documented fixes applied to confirmed errors in the source data, with the
evidence for each.

Every correction was verified against the legacy workbook, whose vote counts
match the source exactly — only the labels differ. The dominant upstream error
is OpenElections reading the "(I)" incumbency marker in a candidate name as
the party "Independent".

A row with status NO_MATCH means the correction no longer matches any source
row, usually because the upstream data was fixed; that entry should be retired.$$;

COMMENT ON COLUMN fdga.corrections.correction IS 'Short label: cycle/office/target and what changed.';
COMMENT ON COLUMN fdga.corrections.rows_matched IS 'How many fact rows this correction touched on the most recent build.';
COMMENT ON COLUMN fdga.corrections.status IS 'APPLIED when the correction matched rows; NO_MATCH when it matched none, which usually means the upstream source was fixed and this entry can be retired.';
COMMENT ON COLUMN fdga.corrections.evidence IS 'Why this correction is justified, and against what independent source it was verified. A correction without evidence would be a guess.';

COMMENT ON TABLE fdga.name_merges IS
$$Candidate spelling variants that were merged into one candidate.

Several sources spell the same candidate differently BY COUNTY, splitting one
person''s vote across multiple rows and corrupting every derived share. Hank
Johnson appears four ways in the 2012 CD-4 data; Lynn Westmoreland twice in
CD-3, which is why the legacy workbook records him unopposed at 100% while the
raw data showed 85.7%.

Merges are conservative: same election, office, district, party AND surname.$$;

COMMENT ON COLUMN fdga.name_merges.cycle_year IS 'Election cycle in which the merge happened.';
COMMENT ON COLUMN fdga.name_merges.office IS 'Normalized office of the affected contest.';
COMMENT ON COLUMN fdga.name_merges.district IS 'District of the affected contest.';
COMMENT ON COLUMN fdga.name_merges.party IS 'Party of the merged candidate. Merges never cross party lines.';
COMMENT ON COLUMN fdga.name_merges.merged_from IS 'The variant spelling that was replaced.';
COMMENT ON COLUMN fdga.name_merges.merged_into IS 'The canonical spelling kept — the variant carrying the most votes.';
COMMENT ON COLUMN fdga.name_merges.votes_moved IS 'Votes reassigned from the variant spelling to the canonical one.';

COMMENT ON TABLE fdga.validation IS
$$Contract-test results from the most recent build. One row per check.

The legacy workbook had no automated checks — its Ballotpedia check tab was
done by hand, once, in 2019, and the 2024 check was never done. Three separate
audits over six years each found a hardcoded value that had silently replaced
a formula. These checks are the replacement, and they run on every build.

If failing_checks in fdga.v_data_health is above zero, do not trust the load.$$;

COMMENT ON COLUMN fdga.validation.check_name IS 'Which check ran: district_coverage, county_coverage, party_domain, votes_sane, grain_unique, contest_has_votes, votes_reconcile, seat_totals.';
COMMENT ON COLUMN fdga.validation.severity IS 'FAIL a real defect, do not publish. WARN worth a look, not blocking. KNOWN a documented source limitation with a recorded reason. PASS the check succeeded.';
COMMENT ON COLUMN fdga.validation.scope IS 'What the check covered, e.g. 2018/state_house or all.';
COMMENT ON COLUMN fdga.validation.detail IS 'Human-readable result, including the documented reason for anything marked KNOWN.';

COMMENT ON TABLE fdga.reconciliation IS
$$Cell-by-cell agreement with the legacy "Ga Gen Assembly Analysis" workbook —
