COMMENT ON TABLE fdga.facts IS
$$Vote counts at county x contest x candidate grain — the fact table.

Carries only what the source states: no derived flags, no thresholds, no
judgments. Anything requiring a policy decision (what counts as competitive,
what counts as uncontested) is computed in fdga.contests and
fdga.chamber_year, so the rule lives in one place.

Note that legislative districts do NOT nest inside counties. A district
spanning four counties has four rows per candidate. To get a district total,
sum over county — or use fdga.contests, which has already done it.$$;

COMMENT ON COLUMN fdga.facts.election_date IS 'Date of the election, e.g. 2024-11-05.';
COMMENT ON COLUMN fdga.facts.cycle_year IS 'Election cycle, e.g. 2024. Use this for grouping rather than extracting the year from election_date.';
COMMENT ON COLUMN fdga.facts.election_type IS 'general, runoff or special. Part of the key: in 2020 the regular U.S. Senate race and the Loeffler/Warnock special were both held on 2020-11-03.';
COMMENT ON COLUMN fdga.facts.office IS 'Normalized office: us_house, state_senate, state_house, president, us_senate, governor. Source spellings vary by cycle ("State House" vs "State Representative") and are normalized on load.';
COMMENT ON COLUMN fdga.facts.district IS 'Zero-padded district number as text, e.g. 001. Empty string for statewide offices — an empty string means "not applicable", it is never NULL. Deliberately text: casting to integer loses the padding and breaks joins to fdga.contests.';
COMMENT ON COLUMN fdga.facts.county IS 'Georgia county name in title case. "Unknown" holds votes the source could not attribute to a county (11 write-in rows in 2006).';
COMMENT ON COLUMN fdga.facts.candidate_name IS 'Candidate name as printed by the source, whitespace normalized. Spelling variants of the same person within one contest have been merged — see fdga.name_merges.';
COMMENT ON COLUMN fdga.facts.party_raw IS 'Party string exactly as the source wrote it, kept for audit. Values vary wildly by cycle: Republican, REP, R, and a stray-paren artifact "(REP" all appear.';
COMMENT ON COLUMN fdga.facts.party IS 'Normalized party: R Republican, D Democratic, L Libertarian, G Green, I Independent, W Write-In, N Nonpartisan, O Other.';
COMMENT ON COLUMN fdga.facts.votes IS 'Votes cast for this candidate in this county for this contest. Never negative.';
COMMENT ON COLUMN fdga.facts.source_id IS 'Which source file set produced this row. Join to fdga.manifest for provenance and checksum.';
COMMENT ON COLUMN fdga.facts.source_row IS 'Row index within the source file, for tracing a value back to its origin line.';

