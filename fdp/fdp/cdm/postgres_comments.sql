-- Schema
-- ===========================================================================

COMMENT ON SCHEMA fdga IS
$$Georgia election results, 2000-2024. Congressional, state legislative and
statewide races, at county x contest x candidate grain.

Generated by fdp/scripts/build_fdga_cdm.py from OpenElections source files and
published here by load_fdga_to_postgres.py. Every load truncates and rewrites —
do not edit by hand, and do not create objects in this schema that a reload
would destroy.

Start with the v_ views rather than the raw tables: they carry friendly labels
and present percentages as percentages.$$;

