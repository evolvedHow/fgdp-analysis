COMMENT ON COLUMN fdga.reconciliation.cycle_year IS 'Election cycle compared.';
COMMENT ON COLUMN fdga.reconciliation.chamber IS 'Chamber compared.';
COMMENT ON COLUMN fdga.reconciliation.field IS 'Which measure was compared: seats_r, seats_d, races_uncontested or races_competitive.';
